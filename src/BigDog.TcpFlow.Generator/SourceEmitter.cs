using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace BigDog.TcpFlow.Generator;

/// <summary>Renders <c>FlowTypes.g.cs</c>: the type registry, one MemoryPack formatter per shape, and their registration.</summary>
internal static class SourceEmitter
{
    public static string Render(IReadOnlyList<FlowTypeModel> flowTypes, IReadOnlyList<ShapeModel> shapes, IReadOnlyList<RegistrationModel> registrations)
    {
        var version = typeof(SourceEmitter).Assembly.GetName().Version?.ToString() ?? "0.0.0";
        var source = new StringBuilder();
        source.Append($$"""
            // <auto-generated/>
            #nullable enable annotations
            #nullable disable warnings
            #pragma warning disable CA2255 // ModuleInitializer in a library: intentional, it registers this assembly's flow types.

            namespace BigDog.TcpFlow
            {
                /// <summary>Flow types discovered by the TcpFlow source generator in this project and its references.</summary>
                [global::System.CodeDom.Compiler.GeneratedCode("BigDog.TcpFlow.Generator", "{{version}}")]
                internal static class FlowTypes
                {
                    /// <summary>A registry containing exactly the discovered flow types.</summary>
                    public static global::BigDog.TcpFlow.FlowTypeRegistry Registry { get; } = Create();

                    private static global::BigDog.TcpFlow.FlowTypeRegistry Create()
                    {
                        var registry = new global::BigDog.TcpFlow.FlowTypeRegistry();

            """);

        foreach (var type in flowTypes)
            source.AppendLine($"""            registry.Add(global::BigDog.TcpFlow.FlowTypeInfo.Create<{type.FullName}>(0x{type.Id:X8}u, "{type.QualifiedName}"));""");

        source.Append("""
                        return registry;
                    }

                    /// <summary>
                    /// Registers the generated MemoryPack formatters and adds this project's flow types to
                    /// <see cref="global::BigDog.TcpFlow.FlowTypeRegistry.Default"/> when the assembly loads.
                    /// </summary>
                    [global::System.Runtime.CompilerServices.ModuleInitializer]
                    internal static void Initialize()
                    {

            """);

        foreach (var shape in shapes)
            source.AppendLine($"            Register(new global::BigDog.TcpFlow.Generated.{shape.FormatterName}());");
        foreach (var registration in registrations)
            source.AppendLine($"            Register(new {registration.FormatterType}());");

        source.Append("""
                        global::BigDog.TcpFlow.FlowTypeRegistry.Default.Add(Registry);
                    }

                    private static void Register<T>(global::MemoryPack.MemoryPackFormatter<T> formatter)
                    {
                        if (!global::MemoryPack.MemoryPackFormatterProvider.IsRegistered<T>())
                            global::MemoryPack.MemoryPackFormatterProvider.Register(formatter);
                    }
                }
            }

            namespace BigDog.TcpFlow.Generated
            {

            """);

        foreach (var shape in shapes)
            RenderFormatter(source, shape);

        source.AppendLine("}");
        return source.ToString();
    }

    private static void RenderFormatter(StringBuilder source, ShapeModel shape)
    {
        var type = shape.FullName;
        var valueType = shape.IsValueType ? type : type + "?";
        var count = shape.Members.Length;
        var members = shape.Members.ToList();

        source.AppendLine($$"""
                /// <summary>Generated MemoryPack formatter for <see cref="{{type}}"/>.</summary>
                [global::System.CodeDom.Compiler.GeneratedCode("BigDog.TcpFlow.Generator", null)]
                internal sealed class {{shape.FormatterName}} : global::MemoryPack.MemoryPackFormatter<{{type}}>
                {
                    public override void Serialize<TBufferWriter>(ref global::MemoryPack.MemoryPackWriter<TBufferWriter> writer, scoped ref {{valueType}} value)
                    {
            """);

        if (!shape.IsValueType)
        {
            source.AppendLine("""
                            if (value is null)
                            {
                                writer.WriteNullObjectHeader();
                                return;
                            }

                """);
        }

        source.AppendLine($"            writer.WriteObjectHeader({count});");
        foreach (var member in members)
            source.AppendLine("            " + WriteCall(member));

        source.AppendLine($$"""
                    }

                    public override void Deserialize(ref global::MemoryPack.MemoryPackReader reader, scoped ref {{valueType}} value)
                    {
                        if (!reader.TryReadObjectHeader(out var count))
                        {
                            value = default;
                            return;
                        }
                        if (count > {{count}})
                            global::MemoryPack.MemoryPackSerializationException.ThrowInvalidPropertyCount(typeof({{type}}), {{count}}, count);

            """);

        // Members missing from an older sender's (shorter) object keep their default values.
        foreach (var member in members)
            source.AppendLine($"            {member.TypeName} __{member.Name} = default!;");
        for (var i = 0; i < members.Count; i++)
            source.AppendLine($"            if (count > {i}) {ReadCall(members[i])}");

        var initializers = string.Join(", ", members.Select(m => $"@{m.Name} = __{m.Name}"));
        source.AppendLine($$"""

                        value = new {{type}} { {{initializers}} };
                    }
                }

            """);
    }

    private static string WriteCall(MemberModel member) => member.Kind switch
    {
        MemberKind.String => $"writer.WriteString(value.@{member.Name});",
        // Nullable<T> doesn't satisfy C#'s `unmanaged` constraint; MemoryPack's own generator uses the Dangerous* variants too.
        MemberKind.Unmanaged when member.TypeName.EndsWith("?") => $"writer.DangerousWriteUnmanaged(value.@{member.Name});",
        MemberKind.Unmanaged => $"writer.WriteUnmanaged(value.@{member.Name});",
        MemberKind.UnmanagedArray => $"writer.WriteUnmanagedArray(value.@{member.Name});",
        MemberKind.Array => $"writer.WriteArray(value.@{member.Name});",
        _ => $"writer.WriteValue(value.@{member.Name});",
    };

    private static string ReadCall(MemberModel member) => member.Kind switch
    {
        MemberKind.String => $"__{member.Name} = reader.ReadString();",
        MemberKind.Unmanaged when member.TypeName.EndsWith("?") => $"reader.DangerousReadUnmanaged(out __{member.Name});",
        MemberKind.Unmanaged => $"reader.ReadUnmanaged(out __{member.Name});",
        MemberKind.UnmanagedArray => $"__{member.Name} = reader.ReadUnmanagedArray<{member.ElementTypeName}>();",
        MemberKind.Array => $"__{member.Name} = reader.ReadArray<{member.ElementTypeName}>();",
        _ => $"__{member.Name} = reader.ReadValue<{member.TypeName}>();",
    };
}
